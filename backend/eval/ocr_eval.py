"""
OCR extraction evaluation.

    cd backend
    python -m eval.ocr_eval                        # documents listed in eval/manifest.json
    python -m eval.ocr_eval --include-synthetic    # + generated regression documents (reported separately)
    python -m eval.ocr_eval --validate-only        # check the manifest, run nothing
    python -m eval.ocr_eval --strict               # non-zero exit if the manifest has problems or authorization is unconfirmed
    python -m eval.ocr_eval --json out.json

What is measured, per report type and never pooled across real and synthetic documents:

  numeric accuracy      read value == human-verified value                (misses count as wrong)
  value|found           the same, over only the fields that were found
  unit accuracy         read unit == verified unit, ONLY where the report states a unit next to the value
  completeness          fields found / fields expected
  review routing        every expected field lands in exactly one bucket:
      auto_correct   marked "valid" (would be saved without a human) and right
      AUTO_WRONG     marked "valid" and WRONG  <- the dangerous case; its rate is the headline safety number
      review_wrong   wrong, but routed to a human (the safety net worked)
      review_right   right, but routed to a human anyway (costs the farmer a click)
      missing        not found (the farmer must enter it)
  catch rate            wrong reads that reached a human / all wrong reads

Every proportion is printed with its count and a 95% Wilson interval. A report type with fewer than MIN_DOCS documents is
labelled INSUFFICIENT SAMPLE: its numbers describe those documents, not the population of lab reports.

Honesty rules:
  * Ground truth is whatever the manifest says; each entry must name who verified it and on what authority the document
    may be used (`authorization_confirmed`). Unconfirmed authorization is printed on every run.
  * Documents are never invented or "completed" here. Synthetic regression documents are generated by the test helpers
    and are labelled as such.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import sys
from collections import defaultdict
from datetime import date, datetime
from pathlib import Path

from app.ocr import validator
from app.ocr.pipeline import run_pipeline
from app.ocr.schemas import CANONICAL_PARAMETERS, EXTRA_PARAMETERS, MICRONUTRIENT_PARAMETERS, all_fields

HERE = Path(__file__).parent
MIN_DOCS = 30  # heuristic floor below which a per-report-type figure is not a population estimate
REPORT_TYPES = ("digital_pdf", "scanned_pdf", "scanned_image", "photo_image")
KNOWN_PARAMETERS = (*CANONICAL_PARAMETERS, *EXTRA_PARAMETERS, *MICRONUTRIENT_PARAMETERS)
# Units a ground-truth entry may declare for each parameter (the validator's target unit and its equivalents).
_EQUIV = validator._UNIT_EQUIVALENTS


def allowed_units(parameter: str) -> set[str | None]:
    if parameter in ("phosphorus_pentoxide", "potassium_oxide"):
        return {"kg/ha", None}
    target = validator.TARGET_UNIT.get(parameter)
    if target is None:
        return {None}  # dimensionless (pH)
    return {target, *_EQUIV.get(target, set())}


# ---------------------------------------------------------------- manifest
def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def validate_manifest(manifest: dict, base: Path = HERE) -> list[str]:
    """Everything wrong with the manifest. An entry with problems must not be evaluated."""
    problems: list[str] = []
    if manifest.get("schema_version") != 2:
        problems.append("schema_version must be 2")
    docs = manifest.get("documents")
    if not isinstance(docs, list) or not docs:
        return problems + ["documents must be a non-empty list"]
    seen: set[str] = set()
    for i, d in enumerate(docs):
        tag = f"documents[{i}]" + (f" ({d.get('id')})" if isinstance(d, dict) and d.get("id") else "")
        if not isinstance(d, dict):
            problems.append(f"{tag}: not an object")
            continue

        def need(key: str, kind=str):
            v = d.get(key)
            if not (isinstance(v, kind) and (kind is not str or v.strip())):
                problems.append(f"{tag}: '{key}' is missing or empty")
                return None
            return v

        doc_id = need("id")
        if doc_id in seen:
            problems.append(f"{tag}: duplicate id")
        seen.add(doc_id or f"#{i}")
        if need("report_type") and d["report_type"] not in REPORT_TYPES:
            problems.append(f"{tag}: report_type must be one of {REPORT_TYPES}")
        need("laboratory")
        need("authorization")
        need("verified_by")
        if not isinstance(d.get("authorization_confirmed"), bool):
            problems.append(f"{tag}: authorization_confirmed must be true or false")
        vo = d.get("recorded_on")
        try:
            if vo is None or datetime.strptime(vo, "%Y-%m-%d").date() > date.today():
                raise ValueError
        except (TypeError, ValueError):
            problems.append(f"{tag}: recorded_on must be a past YYYY-MM-DD date")

        file = need("file")
        if file:
            path = (base / file).resolve()
            if not path.exists():
                problems.append(f"{tag}: file not found: {file}")
            else:
                want = d.get("sha256")
                if not (isinstance(want, str) and len(want) == 64):
                    problems.append(f"{tag}: sha256 of the document is required (the ground truth belongs to exactly these bytes)")
                elif sha256_file(path) != want:
                    problems.append(f"{tag}: sha256 does not match the file - the document changed after its ground truth was verified")

        truth = d.get("ground_truth")
        if not isinstance(truth, dict) or not truth:
            problems.append(f"{tag}: ground_truth must be a non-empty object")
            continue
        for param, entry in truth.items():
            where = f"{tag}: ground_truth.{param}"
            if param not in KNOWN_PARAMETERS:
                problems.append(f"{where}: unknown parameter")
                continue
            if not isinstance(entry, dict) or "value" not in entry:
                problems.append(f"{where}: needs a 'value'")
                continue
            v = entry["value"]
            if isinstance(v, bool) or not (isinstance(v, (int, float)) and math.isfinite(v) or (isinstance(v, str) and v[:1] in "<>=" and len(v) > 1)):
                problems.append(f"{where}: value must be a finite number or a bound string like '>5'")
            if entry.get("unit") not in allowed_units(param):
                problems.append(f"{where}: unit '{entry.get('unit')}' is not valid for {param} (allowed: {sorted(u for u in allowed_units(param) if u)} or none)")
            if not isinstance(entry.get("unit_stated"), bool):
                problems.append(f"{where}: unit_stated must say whether the report prints a unit next to the value")
    return problems


def load_manifest(path: Path | None = None) -> dict:
    return json.loads((path or HERE / "manifest.json").read_text(encoding="utf-8"))


# ---------------------------------------------------------------- scoring
def _equal(a, b) -> bool:
    if isinstance(a, (int, float)) and isinstance(b, (int, float)) and not isinstance(a, bool):
        return abs(float(a) - float(b)) < 1e-9
    return a == b


def evaluate_document(name: str, content: bytes, truth: dict, report_type: str = "unknown") -> dict:
    result = run_pipeline(name, content)
    fields = all_fields(result.soil_parameters)
    rows = {}
    for param, expected in truth.items():
        f = fields.get(param)
        read = f.value if f else None
        validation = f.validation if f else "missing"
        found = read is not None
        value_ok = found and _equal(read, expected["value"])
        auto = validation == "valid"
        if not found:
            bucket = "missing"
        elif auto and value_ok:
            bucket = "auto_correct"
        elif auto:
            bucket = "AUTO_WRONG"
        elif value_ok:
            bucket = "review_right"
        else:
            bucket = "review_wrong"
        stated = bool(expected.get("unit_stated"))
        read_stated = bool(f and f.unit_source == "stated")
        rows[param] = {
            "expected": expected["value"], "read": read, "value_ok": value_ok, "found": found,
            "validation": validation, "bucket": bucket,
            "unit_expected": expected.get("unit"), "unit_read": f.unit if f else None,
            "unit_scored": stated, "unit_ok": (stated and read_stated and f.unit == expected.get("unit")) if stated else None,
        }
    return {"name": name, "status": result.status, "report_type": report_type, "rows": rows}


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (0.0, 1.0)
    p = k / n
    d = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / d
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, centre - half), min(1.0, centre + half))


def summarise(docs: list[dict]) -> dict:
    """Aggregate per report type (never across types) and overall for the set."""
    def blank():
        return defaultdict(int)

    by_type: dict[str, dict] = defaultdict(blank)
    per_param: dict[str, dict] = defaultdict(blank)
    docs_per_type: dict[str, int] = defaultdict(int)
    for d in docs:
        docs_per_type[d["report_type"]] += 1
        for param, r in d["rows"].items():
            for bucket in (by_type[d["report_type"]], per_param[param]):
                bucket["n"] += 1
                bucket["found"] += int(r["found"])
                bucket["value_ok"] += int(r["value_ok"])
                bucket[r["bucket"]] += 1
                if r["unit_scored"]:
                    bucket["unit_n"] += 1
                    bucket["unit_ok"] += int(bool(r["unit_ok"]))
    return {
        "documents_per_report_type": dict(docs_per_type),
        "by_report_type": {k: dict(v) for k, v in by_type.items()},
        "per_parameter": {k: dict(v) for k, v in per_param.items()},
    }


def _prop(k: int, n: int) -> str:
    if n == 0:
        return "n/a (0 fields)"
    lo, hi = wilson(k, n)
    return f"{k}/{n} = {100 * k / n:.0f}%  (95% CI {100 * lo:.0f}-{100 * hi:.0f}%)"


def render(title: str, docs: list[dict], summary: dict) -> str:
    out = [f"\n== {title}: {len(docs)} document(s) =="]
    for d in docs:
        out.append(f"  {d['name']} [{d['report_type']}]: pipeline status = {d['status']}")
    for rtype, t in sorted(summary["by_report_type"].items()):
        nd = summary["documents_per_report_type"][rtype]
        verdict = "INSUFFICIENT SAMPLE - describes these documents only, NOT an accuracy estimate" if nd < MIN_DOCS else "sample size above the heuristic floor"
        wrong = t.get("AUTO_WRONG", 0) + t.get("review_wrong", 0)
        auto = t.get("auto_correct", 0) + t.get("AUTO_WRONG", 0)
        out += [
            f"  -- report type '{rtype}': {nd} document(s) (floor {MIN_DOCS}), {t['n']} ground-truth field(s) -- {verdict}",
            f"     numeric accuracy (misses = wrong)  {_prop(t['value_ok'], t['n'])}",
            f"     value accuracy | found             {_prop(t['value_ok'], t['found'])}",
            f"     unit accuracy (stated units only)  {_prop(t.get('unit_ok', 0), t.get('unit_n', 0))}",
            f"     completeness (found)               {_prop(t['found'], t['n'])}",
            f"     routing: auto_correct={t.get('auto_correct', 0)}  AUTO_WRONG={t.get('AUTO_WRONG', 0)}  review_wrong={t.get('review_wrong', 0)}  review_right={t.get('review_right', 0)}  missing={t.get('missing', 0)}",
            f"     wrong auto-accepted / auto-accepted {_prop(t.get('AUTO_WRONG', 0), auto)}",
            f"     wrong reads caught by review       {_prop(t.get('review_wrong', 0), wrong)}",
            f"     needed a human (review or missing) {_prop(t['n'] - auto, t['n'])}",
        ]
    out.append("  per parameter (value ok / n | AUTO_WRONG):")
    for p, v in sorted(summary["per_parameter"].items()):
        out.append(f"    {p:24s} {v['value_ok']}/{v['n']} | {v.get('AUTO_WRONG', 0)}")
    wrong_rows = [(d["name"], p, r) for d in docs for p, r in d["rows"].items() if not r["value_ok"]]
    if wrong_rows:
        out.append("  not read correctly:")
        for name, p, r in wrong_rows:
            out.append(f"    {name}: {p} expected {r['expected']!r}, read {r['read']!r} -> {r['bucket']}")
    return "\n".join(out)


# ---------------------------------------------------------------- synthetic regression documents
def synthetic_documents() -> list[tuple[str, str, bytes, dict]]:
    """(name, report_type, bytes, truth) generated by the test helpers. Regression only; never mixed with real documents."""
    sys.path.insert(0, str(HERE.parent))
    from tests.fixtures import soil_report_files as fx

    v = fx.SAMPLE_VALUES
    truth = {
        "nitrogen": {"value": v["nitrogen"], "unit": "kg/ha", "unit_stated": True},
        "phosphorus": {"value": v["phosphorus"], "unit": "kg/ha", "unit_stated": True},
        "potassium": {"value": v["potassium"], "unit": "kg/ha", "unit_stated": True},
        "ph": {"value": v["ph"], "unit": None, "unit_stated": False},
        "electrical_conductivity": {"value": v["electrical_conductivity"], "unit": "dS/m", "unit_stated": True},
        "organic_carbon": {"value": v["organic_carbon"], "unit": "%", "unit_stated": True},
    }
    return [
        ("synthetic text-layer PDF", "digital_pdf", fx.text_layer_pdf_bytes(), truth),
        ("synthetic scanned PDF (Tesseract)", "scanned_pdf", fx.scanned_pdf_bytes(), truth),
    ]


# ---------------------------------------------------------------- CLI
def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--include-synthetic", action="store_true")
    ap.add_argument("--validate-only", action="store_true")
    ap.add_argument("--strict", action="store_true")
    ap.add_argument("--manifest", type=Path)
    ap.add_argument("--json", type=Path)
    args = ap.parse_args()

    manifest = load_manifest(args.manifest)
    problems = validate_manifest(manifest, (args.manifest.parent if args.manifest else HERE))
    for p in problems:
        print(f"MANIFEST PROBLEM: {p}", file=sys.stderr)
    unconfirmed = [d.get("id") for d in manifest.get("documents", []) if isinstance(d, dict) and d.get("authorization_confirmed") is not True]
    for u in unconfirmed:
        print(f"WARNING: authorization to use '{u}' for evaluation is NOT confirmed", file=sys.stderr)
    if problems or (args.strict and unconfirmed):
        return 2
    if args.validate_only:
        print(f"manifest OK: {len(manifest['documents'])} document(s)")
        return 0

    real = []
    base = args.manifest.parent if args.manifest else HERE
    for entry in manifest["documents"]:
        path = (base / entry["file"]).resolve()
        d = evaluate_document(path.name, path.read_bytes(), entry["ground_truth"], entry["report_type"])
        d.update(name=entry["id"], verified_by=entry["verified_by"], authorization_confirmed=entry["authorization_confirmed"])
        real.append(d)

    report = {"real": {"documents": real, "summary": summarise(real)}}
    print(render("REAL documents", real, report["real"]["summary"]))
    for d in real:
        print(f"  ground truth for {d['name']} verified by: {d['verified_by']} | authorization confirmed: {d['authorization_confirmed']}")

    if args.include_synthetic:
        syn = []
        for name, rtype, content, truth in synthetic_documents():
            d = evaluate_document(name, content, truth, rtype)
            d["name"] = name
            syn.append(d)
        report["synthetic"] = {"documents": syn, "summary": summarise(syn)}
        print(render("SYNTHETIC documents (generated for regression; NOT evidence of real-world accuracy)", syn, report["synthetic"]["summary"]))

    if args.json:
        args.json.write_text(json.dumps(report, indent=2, default=str), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
